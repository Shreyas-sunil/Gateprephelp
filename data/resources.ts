/** Default video playlist and PYQ source per subject, used to attach links to generated plan tasks. */
export const SUBJECT_LINKS: Partial<Record<string, { video?: string; pyq?: string }>> = Object.fromEntries(
  (["em", "dl", "coa", "pds", "algo", "toc", "cd", "os", "db", "cn"] as const).map((sid) => [
    sid,
    {
      video: BUILTIN_RESOURCES.find((r) => r.id.startsWith("yt-go-") && r.subjectIds[0] === sid)?.url,
      pyq: "https://practicepaper.in/gate-cse/gate-cse-subject-wise-questions",
    },
  ]),
);

export function videoForTopic(topicId: string | undefined, subjectId: string | undefined): string | undefined {
  if (topicId) {
    const hit = BUILTIN_RESOURCES.find((r) => r.type === "video" && r.id.startsWith("yt-go-") && r.topicIds.includes(topicId));
    if (hit) return hit.url;
  }
  return subjectId ? SUBJECT_LINKS[subjectId]?.video : undefined;
}
